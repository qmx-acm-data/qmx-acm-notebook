'use strict';

const assert=require('node:assert/strict');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');

(async()=>{const browser=await chromium.launch({channel:'msedge',headless:true});
try{const page=await browser.newPage({viewport:{width:1440,height:940}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
const url=pathToFileURL(path.resolve(__dirname,'../ui/index.html')).href;
await page.goto(url);
await page.waitForSelector('#home-panel:not([hidden])');
await page.mouse.move(700,200);
assert.equal(await page.locator('body').getAttribute('data-view'),'home');
assert.deepEqual(await page.locator('.sidebar .nav-item').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('aria-label'))),['主页','tricks','公共题库','算法笔记','个人收藏']);
assert.deepEqual(await page.locator('.rail-nav-item').evaluateAll(nodes=>nodes.map(n=>getComputedStyle(n).borderTopWidth)),Array(5).fill('0px'),'compact buttons have no native black border');
assert.equal(await page.locator('.sidebar-drawer').evaluate(n=>getComputedStyle(n).transitionDuration.split(',')[0].trim()),'0.3s');
assert.equal(await page.locator('.sidebar-drawer').evaluate(n=>getComputedStyle(n).boxShadow),'none');
await page.emulateMedia({reducedMotion:'reduce'});
assert.equal(await page.locator('.sidebar-drawer').evaluate(n=>getComputedStyle(n).transitionDuration.split(',')[0].trim()),'0.3s','explicit slide survives global reduced-motion override');
await page.emulateMedia({reducedMotion:'no-preference'});
const width=()=>page.locator('.sidebar').evaluate(n=>Math.round(n.getBoundingClientRect().width));
await page.waitForFunction(()=>Math.round(document.querySelector('.sidebar').getBoundingClientRect().width)===72);
const left=await page.locator('.workspace').evaluate(n=>n.getBoundingClientRect().left);
// A quick pass should not open the rail; leaving starts closing immediately.
await page.clock.install();
await page.dispatchEvent('.sidebar','pointerenter',{pointerType:'mouse'});
await page.clock.runFor(60);
assert.equal(await page.locator('body').evaluate(n=>n.classList.contains('sidebar-open')),false);
await page.dispatchEvent('.sidebar','pointerleave',{pointerType:'mouse'});
await page.clock.runFor(400);
assert.equal(await page.locator('body').evaluate(n=>n.classList.contains('sidebar-open')),false);
await page.dispatchEvent('.sidebar','pointerenter',{pointerType:'mouse'});
await page.clock.runFor(110);
assert.equal(await page.locator('body').evaluate(n=>n.classList.contains('sidebar-open')),true);
await page.dispatchEvent('.sidebar','pointerleave',{pointerType:'mouse'});
assert.equal(await page.locator('body').evaluate(n=>n.classList.contains('sidebar-open')),false,'leave closes immediately without advancing timers');
await page.dispatchEvent('.sidebar','pointerenter',{pointerType:'mouse'});
await page.clock.runFor(300);
assert.equal(await page.locator('body').evaluate(n=>n.classList.contains('sidebar-open')),true,'return opens again');
await page.dispatchEvent('.sidebar','pointerleave',{pointerType:'mouse'});
await page.clock.runFor(550);
await page.clock.resume();
await page.waitForFunction(()=>Math.round(document.querySelector('.sidebar').getBoundingClientRect().width)===72);
await page.hover('.sidebar');
await page.waitForFunction(()=>getComputedStyle(document.querySelector('.sidebar-drawer')).transform==='matrix(1, 0, 0, 1, 0, 0)');
await page.waitForFunction(()=>Math.round(document.querySelector('.sidebar').getBoundingClientRect().width)===232);
assert.equal(await page.locator('.workspace').evaluate(n=>n.getBoundingClientRect().left),left,'hover overlays without moving content');
assert(await page.locator('.sidebar-drawer .nav-label').evaluateAll(nodes=>nodes.every(n=>{const r=n.getBoundingClientRect(),v=document.querySelector('.sidebar-slide-viewport').getBoundingClientRect();return r.width>0&&r.left>=v.left&&r.right<=v.right;})),'expanded labels fit entirely within text viewport');
await page.mouse.move(220,450);
assert.equal(await width(),232,'expanded area keeps hover open');
await page.mouse.move(500,450);
await page.waitForFunction(()=>{const d=document.querySelector('.sidebar-drawer');const x=new DOMMatrixReadOnly(getComputedStyle(d).transform).m41;return x< -1 && x> -231;});
assert.equal(await page.locator('.sidebar-drawer').evaluate(n=>Math.round(n.getBoundingClientRect().width)),160,'text extension keeps its width while sliding');
assert.equal(await page.locator('.sidebar-drawer .nav-label').first().evaluate(n=>getComputedStyle(n).opacity),'1','text slides with drawer rather than fading');
await page.waitForFunction(()=>getComputedStyle(document.querySelector('.sidebar-drawer')).visibility==='hidden');
await page.waitForFunction(()=>Math.round(document.querySelector('.sidebar').getBoundingClientRect().width)===72);
await page.hover('.sidebar');
await page.click('#sidebar-toggle');
await page.mouse.move(700,200);
await page.waitForFunction(()=>document.body.classList.contains('sidebar-pinned'));
assert.equal(await page.locator('#sidebar-toggle').getAttribute('aria-pressed'),'true');
await page.waitForFunction(()=>document.querySelector('.workspace').getBoundingClientRect().left===232);
await page.reload();
await page.waitForSelector('#home-panel:not([hidden])');
assert.equal(await page.locator('#sidebar-toggle').getAttribute('aria-pressed'),'true','pin survives restart');
await page.click('#sidebar-toggle');
await page.mouse.move(700,200);
await page.waitForFunction(()=>Math.round(document.querySelector('.sidebar').getBoundingClientRect().width)===72);
for(const view of ['tricks','algorithms','public','favorites','home']){await page.hover('.sidebar');
await page.waitForFunction(()=>getComputedStyle(document.querySelector('.sidebar-drawer')).transform==='matrix(1, 0, 0, 1, 0, 0)');
await page.click(`.nav-item[data-view="${view}"]`);
assert.equal(await page.locator('body').getAttribute('data-view'),view);
assert.equal(await page.locator(`.nav-item[data-view="${view}"]`).getAttribute('aria-current'),'page');
if(view==='tricks')assert.equal(await page.locator('#section-placeholder').isVisible(),true);
if(view==='algorithms')assert.equal(await page.locator('#algorithm-panel').isVisible(),true);
}
assert.equal(await page.locator('[data-view="mine"], [data-view="stats"], [data-view="discussion"], #stats-panel').count(),0,'removed sections have no navigation or rendering targets');
await page.click('#submit-button');
await page.fill('#submit-dialog [name="url"]','https://codeforces.com/problemset/problem/1/A');
await page.fill('#submit-dialog [name="title"]','Saved local reader');
await page.fill('#record-body','## Preserved local Markdown\n\nLocal save stays accessible through its reader and favorites.');
await page.click('#save-local-button');
await page.waitForSelector('body.reading-detail #detail-back-button');
assert.equal(await page.locator('body').getAttribute('data-view'),'public','saving never returns to a removed section');
assert.match(await page.locator('#detail-panel').innerText(),/Saved local reader/);
await page.getByRole('button',{name:'☆ 收藏',exact:true}).click();
await page.getByRole('button',{name:'★ 已收藏',exact:true}).waitFor();
await page.click('#edit-record-button');
assert.match(await page.inputValue('#record-body'),/Preserved local Markdown/);
await page.fill('#record-body','## Edited local Markdown');
await page.click('#save-local-button');
await page.waitForSelector('body.reading-detail #detail-back-button');
assert.match(await page.locator('#detail-panel').innerText(),/Edited local Markdown/);
await page.click('#detail-back-button');
assert.doesNotMatch(await page.locator('#record-list').innerText(),/Saved local reader/,'public library still excludes local records');
await page.locator('.rail-nav-item[data-view="favorites"]').click();
assert.match(await page.locator('#record-list').innerText(),/Saved local reader/);
await page.reload();
await page.locator('.rail-nav-item[data-view="favorites"]').click();
await page.getByRole('button',{name:/Saved local reader/}).click();
assert.match(await page.locator('#detail-panel').innerText(),/Edited local Markdown/,'saved local content remains accessible after reload');
await page.hover('.sidebar');
await page.locator('.brand').click();
assert.equal(await page.locator('body').getAttribute('data-view'),'home');
await page.mouse.move(700,200);
await page.keyboard.press('Tab');
await page.locator('.rail-nav-item[data-view="home"]').focus();
await page.waitForFunction(()=>document.body.classList.contains('sidebar-open'));
// Rail focus must stay in DOM order; redirecting into drawer clones traps Shift+Tab.
await page.locator('.rail-nav-item[data-view="favorites"]').focus();
await page.keyboard.press('Enter');
assert.equal(await page.locator('body').getAttribute('data-view'),'favorites','keyboard activation routes from the compact rail');
assert(await page.locator('.rail-nav-item[data-view="favorites"]').evaluate(n=>n===document.activeElement),'keyboard focus stays on the rail control');
for(const selector of ['.rail-nav-item[data-view="algorithms"]','.rail-nav-item[data-view="public"]','.rail-nav-item[data-view="tricks"]','.rail-nav-item[data-view="home"]','#sidebar-toggle','.rail-brand']){
await page.keyboard.press('Shift+Tab');
assert(await page.locator(selector).evaluate(n=>n===document.activeElement),`reverse traversal reaches ${selector} without looping through drawer clones`);
}
await page.keyboard.press('Enter');
assert.equal(await page.locator('body').getAttribute('data-view'),'home','keyboard brand activation returns home');
await page.locator('#settings-button').focus();
await page.waitForFunction(()=>!document.body.classList.contains('sidebar-open'));
await page.setViewportSize({width:390,height:844});
await page.mouse.move(350,200);
await page.waitForFunction(()=>Math.round(document.querySelector('.sidebar').getBoundingClientRect().width)===60);
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'narrow window has no page overflow');
await page.hover('.sidebar');
await page.locator('#sidebar-toggle').click();
await page.mouse.move(350,200);
await page.waitForFunction(()=>document.querySelector('.workspace').getBoundingClientRect().left===60);
assert.equal(await page.locator('.workspace').evaluate(n=>n.getBoundingClientRect().left),60,'narrow pin overlays');
await page.screenshot({path:path.resolve(__dirname,'../screenshots/navigation-narrow.png'),fullPage:true});
await page.setViewportSize({width:1440,height:940});
await page.locator('#sidebar-toggle').click();
await page.mouse.move(700,200);
await page.waitForFunction(()=>Math.round(document.querySelector('.sidebar').getBoundingClientRect().width)===72);
await page.screenshot({path:path.resolve(__dirname,'../screenshots/navigation-home.png'),fullPage:true});
assert.deepEqual(errors,[]);
console.log('NAVIGATION PASS: default home, exact sections, compact/hover/leave, overlay, pin persistence, cancel pin, keyboard, shortcuts, narrow layout');
}finally{await browser.close();
}})().catch(e=>{console.error(e);
process.exitCode=1;
});

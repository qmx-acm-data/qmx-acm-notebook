'use strict';
// data/algorithm-directory.json is the editable source. No network or captured page is needed.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
function build({ check = false } = {}) {
  const data = JSON.parse(fs.readFileSync(path.join(root, 'data/algorithm-directory.json'), 'utf8'));
  assert.equal(data.schema, 1);
  const ids = new Set(), legacy = new Map(), headings = [], flat = [];
  const difficulties = new Set(['basic', 'beginner', 'intermediate', 'advanced', 'expert']);
  function visit(n, depth) {
    assert.equal(typeof n.id, 'string'); assert.ok(n.id && !ids.has(n.id), `Duplicate node ID ${n.id}`); ids.add(n.id);
    assert.equal(typeof n.label, 'string'); assert.ok(n.label.trim());
    assert.equal(n.level, depth); assert.ok(Array.isArray(n.children));
    if (['directory', 'category'].includes(n.kind)) {
      assert.equal(n.color, 'parent', `Directory must not carry difficulty ${n.label}`);
      assert.equal(n.rating?.status, 'not-applicable', `Directory rating must not apply ${n.label}`);
      assert.equal(n.rating?.type, 'directory');
      assert.equal(n.rating?.range, undefined, `Directory has no displayed difficulty range ${n.label}`);
    } else {
      assert.ok(difficulties.has(n.color), `Missing or invalid finalized difficulty ${n.label}`);
      assert.equal(n.rating?.status, 'confirmed', `Unconfirmed difficulty ${n.label}`);
      assert.ok(['knowledge', 'model'].includes(n.rating?.type));
    }
    assert.ok(n.rating.scope.length >= 8 && n.rating.rationale.length > 15, `Unspecified rating scope ${n.label}`);
    assert.ok((n.attributes || []).every(v => ['board', 'useful', 'useless'].includes(v)), `Invalid attribute ${n.label}`);
    if (n.color !== 'parent') assert.ok(n.difficultySource?.kind, `Missing difficulty provenance ${n.label}`);
    if (!n.children.length && !['directory', 'reference'].includes(n.kind)) assert.ok(difficulties.has(n.color), `Unrated algorithm ${n.label}`);
    if(n.sourceHeading)headings.push(n.sourceHeading);
    for(const alias of n.legacyIds || []){assert.ok(!legacy.has(alias), `Duplicate legacy ID ${alias}`);legacy.set(alias,n.id);}
    flat.push(n); n.children.forEach(child => visit(child, depth + 1));
  }
  visit(data.tree, 0);
  assert.deepEqual(data.tree.children.map(n => n.part), Array.from({length:10}, (_,i)=>String(i)));
  assert.equal(headings.length, 126);
  if (data.sourceIndex) {
    assert.equal(data.sourceIndex.length, 126);
    assert.equal(new Set(data.sourceIndex.map(entry => entry.nodeId)).size, 126);
    assert.deepEqual([...data.sourceIndex.map(entry => entry.sourceHeading)].sort(), [...headings].sort());
    assert.ok(data.sourceIndex.every(entry => ids.has(entry.nodeId)), 'Unresolved source index');
  }
  assert.equal(Object.keys(data.legacyNodeMap).length, 367);
  for(const [oldId,newId] of Object.entries(data.legacyNodeMap)){
    assert.ok(ids.has(newId), `Unresolved old ID ${oldId}`);
    assert.ok(oldId===newId || legacy.get(oldId)===newId, `Missing runtime alias ${oldId}`);
  }
  const fullNames = new Map((data.editorial?.titleSimplification?.changes || []).map(change => [change.nodeId, change.before]));
  function displayTree(node) { return { ...node, fullLabel: node.fullLabel || fullNames.get(node.id) || node.label, children: node.children.map(displayTree) }; }
  const tree = { ...displayTree(data.tree), metadata: { schema: data.schema, sources: data.sources, summary: data.summary, ratingPolicy: data.ratingPolicy, sourceIndex: data.sourceIndex, legacyNodeMap: data.legacyNodeMap } };
  const output = "'use strict';\n// Generated by tools/build-algorithm-directory.cjs from data/algorithm-directory.json.\nconst algorithmTree = " + JSON.stringify(tree, null, 2) + ";\nif (typeof module !== 'undefined') module.exports = algorithmTree;\nif (typeof window !== 'undefined') window.QMX_ALGORITHM_TREE = algorithmTree;\n";
  const destination = path.join(root, 'ui/algorithm-tree.js');
  if (check) assert.equal(fs.readFileSync(destination,'utf8').replace(/\r\n/g,'\n'), output, 'Generated algorithm tree differs; run node tools/build-algorithm-directory.cjs');
  else fs.writeFileSync(destination, output);
  return {nodes:flat.length,headings:headings.length,legacyIds:Object.keys(data.legacyNodeMap).length};
}
if(require.main===module){try{console.log(JSON.stringify(build({check:process.argv.includes('--check')})));}catch(error){console.error(error.message);process.exitCode=1;}}
module.exports = { build };
